const TABLES: Record<Locale, Record<string, string>> = { en: EN, fr: FR };

export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const table = TABLES[locale];
  const raw = table[key] ?? EN[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

export function hasKey(locale: Locale, key: string): boolean {
  return key in TABLES[locale];
}

export function formatSummary(
  locale: Locale,
  summaryKey: string,
  params: Record<string, string | number>,
): string {
  const resolved: Record<string, string | number> = { ...params };
  if (typeof params.dest === "string") {
    resolved.dest = t(locale, `container.${params.dest}`);
  }
  if (typeof params.priorKey === "string") {
    const priorParams: Record<string, string | number> = {};
    for (const [name, value] of Object.entries(params)) {
      if (name === "priorKey" || name === "dest") continue;
      priorParams[name] = value;
    }
    if (typeof params.dest === "string") priorParams.dest = params.dest;
    resolved.prior = formatSummary(locale, params.priorKey, priorParams);
  }
  return t(locale, summaryKey, resolved);
}

export function formatEntry(locale: Locale, entry: JournalEntry): string {
  return formatSummary(locale, entry.summaryKey, entry.summaryParams);
}

export function formatVerdict(locale: Locale, verdict: UndoVerdict): string {
  return t(locale, verdict.detailKey, verdict.params);
}
