function at(placeId: string, label?: string): Place {
  const place = placeById(placeId);
  return {
    placeId: place.placeId,
    label: label ?? place.label,
    container: place.container,
    accessible: place.accessible,
  };
}

function item(partial: WorldInstance): WorldInstance {
  return partial;
}

