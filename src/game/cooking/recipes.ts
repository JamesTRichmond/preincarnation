import { STACKING_TABLE, STACKING_VEIN } from "./constants.ts";
import type { Category, EffectSpec, Recipe } from "./types.ts";

const TABLE_NOT =
  "Does not change a fight, a wound, speed, or any number a battle could use.";
const REST_NOT =
  "Does not heal, cure, feed a hunger meter, or restore a body. There is no hunger meter.";
const VEIN_NOT =
  "Does not grant a lasting power, a map you can keep, or any advantage in a fight.";

type EffectDraft = Omit<EffectSpec, "magnitude" | "stacking" | "slot" | "notFor"> & {
  notFor?: string;
};

function recipe(
  draft: Omit<Recipe, "effect"> & { effect: EffectDraft },
): Recipe {
  const slot = draft.category === "vein" ? "vein" : "table";
  const notFor =
    draft.effect.notFor ??
    (draft.category === "vein" ? VEIN_NOT : draft.category === "restorative" ? REST_NOT : TABLE_NOT);
  return {
    ...draft,
    effect: {
      ...draft.effect,
      slot,
      magnitude: 1,
      notFor,
      stacking: slot === "vein" ? STACKING_VEIN : STACKING_TABLE,
    },
  };
}

