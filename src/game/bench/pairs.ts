function subsFor(inputs: { catalogId: string; role: string }[]) {
  const ids = new Set(inputs.filter((i) => i.role === "material").map((i) => i.catalogId));
  return SUBSTITUTIONS.filter((s) => ids.has(s.forCatalogId));
}

export function expandPairs(massOf: (id: string) => number): { items: CatalogEntry[]; recipes: Recipe[] } {
  const items: CatalogEntry[] = [];
  const recipes: Recipe[] = [];
  for (const pair of PAIRS) {
    const inMass = pair.inputs.reduce((sum, [id, qty]) => sum + massOf(id) * qty, 0);
    const yieldMass = pair.yields.reduce((sum, [id, qty]) => sum + massOf(id) * qty, 0);
    if (pair.mass > inMass) {
      throw new Error(`combine creates mass: ${pair.slug} out ${pair.mass} in ${inMass}`);
    }
    if (yieldMass > pair.mass) {
      throw new Error(`dismantle creates mass: ${pair.slug} yield ${yieldMass} item ${pair.mass}`);
    }
    const tags = pair.salvage ? Array.from(new Set([...pair.tags, "salvage-pile"])) : pair.tags;
    items.push({
      id: pair.id,
      fixture: true,
      intendedCatalog: pair.intended,
      name: pair.name,
      kind: pair.kind,
      mass: pair.mass,
      tags,
      blurb: pair.blurb,
    });
    const makeInputs = pair.inputs.map(([catalogId, qty]) => ({
      catalogId,
      qty,
      consume: "all" as const,
      role: "material" as const,
    }));
    recipes.push({
      id: `op.combine.${pair.slug}`,
      kind: "combine",
      name: pair.make.replace(/\.$/, ""),
      summary: pair.make,
      inputs: makeInputs,
      outputs: [{ catalogId: pair.id, qty: 1, identity: "new", condition: 72 }],
      substitutions: subsFor(makeInputs),
      cost: { minutes: pair.kind === "gear" ? 50 : 20, focus: pair.kind === "gear" ? 4 : 2, toolWear: 0 },
      feedback: {
        success: `${pair.make} ${pair.name} is a new object. It does not inherit anyone's history.`,
        fail: "Nothing was spent.",
      },
      failure: {
        onLowCondition: "refuse",
        recovery: "Gather the written materials, or pick a substitute that you actually hold.",
      },
      batchable: true,
      tags: pair.tags,
    });
    const breakInputs = [
      {
        catalogId: pair.id,
        qty: 1,
        consume: "all" as const,
        role: "primary" as const,
        minCondition: 1,
      },
    ];
    recipes.push({
      id: `op.dismantle.${pair.slug}`,
      kind: "dismantle",
      name: pair.unmake.replace(/\.$/, ""),
      summary: pair.unmake,
      inputs: breakInputs,
      outputs: pair.yields.map(([catalogId, qty]) => ({
        catalogId,
        qty,
        identity: "new" as const,
        condition: 60,
      })),
      substitutions: [],
      cost: { minutes: 12, focus: 1, toolWear: 0 },
      feedback: {
        success: `${pair.unmake} ${pair.name} ends as itself. The parts are a lesser mass.`,
        fail: "Nothing was taken apart.",
      },
      failure: {
        onLowCondition: "refuse",
        recovery: "Leave it intact. Breaking a wreck only loses the rest.",
      },
      batchable: true,
      tags: [...pair.tags, ...(pair.salvage ? ["salvage-pile"] : [])],
    });
  }
  return { items, recipes };
}
