const known = (id: string, verb: Verb, label: string, where: string): ItemUse => ({
  id,
  verb,
  label,
  where,
  visibility: "known",
});

const learn = (id: string, verb: Verb, label: string, where: string): ItemUse => ({
  id,
  verb,
  label,
  where,
  visibility: "learnable",
});

type Draft = Pick<ItemDef, "id" | "name" | "kind" | "summary" | "uses"> &
  Partial<Omit<ItemDef, "id" | "name" | "kind" | "summary" | "uses" | "contentClass">>;

function authored(draft: Draft): ItemDef {
  return {
    contentClass: "authored",
    heft: "light",
    stackLimit: 1,
    unique: false,
    protection: "none",
    dismantlable: false,
    modifiable: false,
    tags: [],
    ...draft,
  };
}

