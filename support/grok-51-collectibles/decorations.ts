const byId = new Map(DECORATIONS.map((item) => [item.id, item]));

export function getDecoration(id: string): DecorationDef | undefined {
  return byId.get(id);
}

export function mustDecoration(id: string): DecorationDef {
  const item = byId.get(id);
  if (!item) throw new Error(`Unknown decoration ${id}`);
  return item;
}

export function rotationsFor(kind: SlotKind): number[] {
  if (kind === "wall") return [0, 180];
  return [0, 90, 180, 270];
}

