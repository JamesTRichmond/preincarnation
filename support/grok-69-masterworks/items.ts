export const MASTERWORKS: ItemMeta[] = SEEDS.map((s) => ({
  ...s,
  id: lootId(s.n),
}));

export const ITEM_BY_ID: Record<string, ItemMeta> = Object.fromEntries(MASTERWORKS.map((i) => [i.id, i]));

export const DEMO_IDS = MASTERWORKS.filter((i) => i.demo).map((i) => i.id);

export function itemById(id: string): ItemMeta {
  const item = ITEM_BY_ID[id];
  if (!item) throw new Error(`Unknown masterwork ${id}`);
  return item;
}

export function duplicateHits(): { id: string; name: string; legacy: string }[] {
  const hits: { id: string; name: string; legacy: string }[] = [];
  for (const item of MASTERWORKS) {
    const legacy = semanticDuplicate(item.name);
    if (legacy) hits.push({ id: item.id, name: item.name, legacy });
  }
  return hits;
}
