/** Hand-authored placements outside the Lemon Fair demo grid. Anchors only — map sessions keep their geometry. */

export function item(p) {
  return {
    qty: 1,
    unique: true,
    obtainable: true,
    requiresPrior: false,
    eraAvailable: ["before", "return"],
    questProtected: false,
    ...p,
  };
}

export function C(p) {
  const sourceId = !p.sourceId || p.sourceId === "self" ? p.id : p.sourceId;
  return {
    id: p.id,
    title: p.title,
    districtId: p.districtId,
    siteId: p.siteId,
    dungeonId: p.dungeonId || null,
    venue: p.venue,
    playableInFragment: false,
    mapRef: {
      session: `map/${p.districtId}`,
      layer: p.dungeonId ? "dungeon" : p.layer || "world",
      anchor: `anchor.${p.id}`,
      local: p.local,
      note: "Anchor only. Add this id to the owning map session. Do not overwrite that map, its tiles, or any other session's item catalog.",
    },
    presentation: p.presentation,
    ownership: p.ownership,
    contents: p.contents,
    clue: { text: p.clue, sourceId, honest: true },
    prerequisites: p.prerequisites || [],
    grants: p.grants || { both: [], before: [], return: [] },
    interaction: {
      verb: p.verb,
      successCopy: p.success,
      blockedCopy: p.blocked,
      examinedCopy: p.examined,
      ownedRefusalCopy: p.refusal || "",
      refusalRepeatCopy: p.refusalAgain || "",
      heldCopy: p.held || "",
      rereadCopy: p.reread || "",
    },
    persistence: {
      key: `loot:${p.id}`,
      respawn: "never",
      fixture: !!p.fixture,
      questLock: !!p.quest,
      note: p.note,
    },
    quest: p.quest || null,
    era: p.era,
    environmentalStory: p.story,
    special: null,
    branches: null,
  };
}

export function own(ownerId, ownerName, claim, posture, presentIn = []) {
  return { ownerId, ownerName, claim, posture, presentIn, room: null };
}

export function era(before, ret, change) {
  return {
    before: { state: before, available: true },
    return: { state: ret, available: true, change },
  };
}

