/** 16×16 pixel icons. One palette, one grid, one weight. `.` is empty. */

export const PALETTE = {
  "#": "#16130f",
  p: "#f3ead7",
  c: "#b5523a",
  m: "#2c5c45",
  i: "#6e675e",
} as const;

export type PixelChar = keyof typeof PALETTE | ".";

const D = "................";

function icon(rows: string[]): string[] {
  const padded = rows.map((row) => (row.length > 16 ? row : row.padEnd(16, ".")));
  while (padded.length < 16) padded.push(D);
  if (padded.length !== 16 || padded.some((row) => row.length !== 16)) {
    throw new Error(`Icon must be 16×16, got ${padded.length}×${padded[0]?.length}`);
  }
  return padded;
}

