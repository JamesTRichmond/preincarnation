export const ICON_IDS = Object.keys(PIXELS);

export function assertIconGrid(id: string): void {
  const rows = PIXELS[id];
  if (!rows) throw new Error(`Missing icon ${id}`);
  if (rows.length !== 16) throw new Error(`${id} has ${rows.length} rows`);
  for (const row of rows) {
    if (row.length !== 16) throw new Error(`${id} row width ${row.length}`);
    for (const ch of row) {
      if (ch !== "." && !(ch in PALETTE)) throw new Error(`${id} bad pixel ${ch}`);
    }
  }
}
