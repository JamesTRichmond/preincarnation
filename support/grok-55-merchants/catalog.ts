export const ITEMS: Record<string, ItemDef> = Object.fromEntries(RAW.map((item) => [item.id, item]));

export function item(id: string): ItemDef {
  const found = ITEMS[id];
  if (!found) throw new Error(`Unknown trade item ${id}`);
  return found;
}

export function knownValue(itemId: string, condition: Condition): number {
  const def = item(itemId);
  return Math.max(1, Math.round(def.baseValue * CONDITION_FACTOR[condition]));
}

export function isEssential(itemId: string): boolean {
  return item(itemId).significance === "essential";
}

export const SIGNIFICANCE_LABEL: Record<ItemDef["significance"], string> = {
  common: "Common",
  useful: "Useful",
  named: "Named",
  essential: "Protected",
};
