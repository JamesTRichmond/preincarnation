const PHONE_NOTE =
  "If a browser is launched, the viewport is Chromium emulation only. That is not physical-phone testing.";

function behavior(entry) {
  return {
    kind: "playable-behavior",
    severity: "major",
    notes: "",
    signals: ["preincarnation"],
    measure: null,
    ...entry,
  };
}

function cardinal(id, requirementIds, label, code, axis, sign, facing) {
  const direction = { e: "east", w: "west", n: "north", s: "south" }[facing];
  const assertions = [
    axis === "x"
      ? { op: "delta", path: "x", [sign > 0 ? "gte" : "lte"]: sign > 0 ? 1 : -1 }
      : { op: "delta", path: "y", [sign > 0 ? "gte" : "lte"]: sign > 0 ? 1 : -1 },
    { op: "delta", path: axis === "x" ? "y" : "x", equals: 0 },
    { op: "equals", path: "facing", value: facing },
    { op: "equals", path: "screen", value: "field" },
    { op: "equals", path: "loginRequired", value: false },
  ];
  return behavior({
    id,
    title: `Keyboard move ${direction}`,
    area: "movement-collision",
    requirementIds,
    prerequisites: [
      "Playable field with Ellis Perch controllable.",
      "Clear ground for at least one step in that direction.",
      "Acceptance bindings: WASD and arrow keys, screen-relative. +x is east. +y is south.",
    ],
    steps: [
      "Start a new game and wait until Ellis is on the field.",
      `Press and hold ${label} (${code}) for about 400ms. Do not press another direction.`,
      `Release ${label}.`,
      "Read position and facing.",
    ],
    expected: `Ellis moves ${direction} only. Facing becomes ${facing}. The other axis does not change. No login prompt appears.`,
    script: [
      { type: "new-game" },
      { type: "baseline" },
      { type: "key", phase: "down", code },
      { type: "wait", ms: 400 },
      { type: "key", phase: "up", code },
    ],
    assertions,
    signals: ["preincarnation", "ellis perch"],
  });
}

function touchCardinal(id, dir, axis, sign, facing) {
  return behavior({
    id,
    title: `Touch move ${dir}`,
    area: "touch-simultaneous",
    requirementIds: ["REQ-TOUCH-01"],
    notes: PHONE_NOTE,
    prerequisites: ["Playable field.", "A touch move control is on screen.", "No keyboard keys held."],
    steps: [
      "Start a new game on the field.",
      `Put one finger on the move control and hold ${dir} for about 400ms.`,
      "Lift that finger.",
      "Confirm Ellis moved only on that cardinal and the control is not stuck.",
    ],
    expected: `One touch direction moves Ellis ${dir} (facing ${facing}) and release leaves velocity at rest.`,
    script: [
      { type: "new-game" },
      { type: "baseline" },
      { type: "pointer", phase: "down", id: 1, control: "move", dir: facing },
      { type: "wait", ms: 400 },
      { type: "pointer", phase: "up", id: 1, control: "move" },
      { type: "wait", ms: 150 },
    ],
    assertions: [
      axis === "x"
        ? { op: "delta", path: "x", [sign > 0 ? "gte" : "lte"]: sign > 0 ? 1 : -1 }
        : { op: "delta", path: "y", [sign > 0 ? "gte" : "lte"]: sign > 0 ? 1 : -1 },
      { op: "delta", path: axis === "x" ? "y" : "x", equals: 0 },
      { op: "equals", path: "velocity.x", value: 0 },
      { op: "equals", path: "velocity.y", value: 0 },
    ],
    signals: ["preincarnation"],
  });
}

